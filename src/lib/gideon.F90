module gideon
!< GIDEON, Generated Interpolations and Derivatives, Exact to Order N: the library's entry point.
!<
!< `use gideon` gives the working kinds (R_P, the operators' kind, chosen at build time: gideon_kind_parameters), the
!< stencil rows (gideon_tables) and every operator: one `pure`, device-callable kernel per operator and order, named
!< `gideon_<data>_<op>_<bias><order>` (docs/guide/conventions.md), generated by scripts/gen_gideon.py from rows
!< derived in exact rational arithmetic:
!<
!<    call gideon_fd_d1_c6(q(i-3:i+3), ds, d)      ! first derivative at node i, centred, order 6, point values
!<    call gideon_fv_face_ul3(q(i-2:i), f)         ! value at the face i+1/2 from the three cells on its left
!<    call gideon_fd_d1_c(order, q(i-order/2:i+order/2), ds, d)  ! d1 at node i, the order chosen at run time
use penf, only : I4P, I8P, R4P, R8P
use gideon_kind_parameters
use gideon_tables
use gideon_fd_centred
use gideon_fv_centred
use gideon_fv_upwind
use gideon_deconvolution
use gideon_dispatch
use gideon_operators_3d
implicit none
public
endmodule gideon
