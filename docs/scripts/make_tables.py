# C6: device
# ---------------------------------------------------------------------------------------------------------------------
def device_tables(r: Report) -> None:
    rows = []
    for tag, lab in r.builds():
        p = r.out(tag, 'gideon_test_device')
        where = 'device (OpenACC)' if 'on the device' in p.read_text() else 'host (no OpenACC)'
        line = last_line(p, f'gideon_test_device: {len(r.rows["kernels"])}')  # the summary line
        m = re.search(r'(\d+) kernels, (\d+) values, bitwise (\d+), worst relative difference\s+(\S+), failures (\d+)',
                      line)
        nk, nv, nb, worst, nf = m.groups()
        rows.append([lab, where, nk, nv, f'{nb} ({100 * int(nb) / int(nv):.1f} %)', sci(float(worst)), nf])
    write(VT / 'device-builds.md', table(['Build', 'Where', 'Kernels', 'Values', 'Bitwise equal to the host',
                                          'Worst difference / magnitude', 'Failures'], rows))
    gpu = r.d / 'oac' / 'gpu.txt'
    comp = r.d / 'oac' / 'compiler.txt'
    if gpu.exists():
        name, drv = [s.strip() for s in gpu.read_text().strip().split(',')]
        write(VT / 'device-hardware.md', f'{name} (driver {drv}), {comp.read_text().strip()}.\n')


