# C2: exactness and leading error
# ---------------------------------------------------------------------------------------------------------------------
def exactness_tables(r: Report) -> None:
    ks = r.rows['kernels']
    expected = sum(k['order'] + k['n'] - 1 + 2 for k in ks)  # x^0 .. x^(K+1), K = order + n - 1
    rows = []
    for tag, lab in r.builds():
        line = last_line(r.out(tag, 'gideon_test_tables'), 'gideon_test_tables:')
        nk, checks, fails = ints(line)[:3]
        if checks != expected:
            raise SystemExit(f'{tag}: {checks} checks, the rows give {expected}')
        rows.append([lab, nk, checks, fails])
    write(VT / 'exactness-builds.md', table(['Build', 'Kernels', 'Checks (x^0 … x^(K+1))', 'Failures'], rows))
    det = []
    for k in ks:
        le = Fr(k['leading_error'])
        det.append([f'`{short(k["name"])}`', k['order'], k['order'] + k['n'] - 1, f'$x^{{{k["order"] + k["n"]}}}$',
                    f'${le.numerator}/{le.denominator}$' if le.denominator != 1 else f'${le.numerator}$'])
    grp: dict[tuple, dict[str, Fr]] = defaultdict(dict)
    for k in ks:
        grp[(k['data'], k['op'], k['order'])].setdefault(k['bias'], abs(Fr(k['leading_error'])))
    both = [v for v in grp.values() if 'c' in v and 'ul' in v]
    larger = sum(1 for v in both if v['ul'] > v['c'])
    write(VT / 'exactness-constants.md', f'In {larger} of the {len(both)} groups (data, operator, order) that have '
          'both a centred and an upwind kernel, the upwind $\\vert E\\vert$ is the larger.\n')
    write(VT / 'exactness-leading.md', table(['Kernel', 'Order', 'Exact degree K', 'First monomial missed',
                                              'Exact error on it ($h = 1$)'], det))


