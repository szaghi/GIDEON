# A1: orders
# ---------------------------------------------------------------------------------------------------------------------
def orders_tables(r: Report) -> None:
    ks = r.rows['kernels']
    rows = []
    sums = {}
    for tag, lab in r.builds():
        line = last_line(r.out(tag, 'gideon_test_order'), f'gideon_test_order: {len(r.rows["kernels"])}')
        nk, meas, unres, fails = ints(line)[:4]
        rows.append([lab, nk, meas, unres, fails])
        if tag != 'oac':
            sums[tag] = r.summary(tag)
    write(VT / 'orders-builds.md', table(['Build', 'Kernels', 'Measured (a plateau)', 'Unresolved in this precision',
                                          'Failures'], rows))
    frows = []
    for f, (label, _) in sorted(FAMILY.items(), key=lambda x: x[1][1]):
        g = [short(k['name']) for k in ks if k['family'] == f]
        row = [label, len(g)]
        for tag in ('r32', 'r64', 'r128'):
            if tag in sums:
                row.append(sum(1 for n in g if sums[tag][n]['status'] == 'measured'))
        q = sums.get('r128')
        if q:
            dev = [min(float(q[n]['p1']), float(q[n]['p2'])) - int(q[n]['design']) for n in g]
            row.append(f'{min(dev):+.3f}')
        frows.append(row)
    hdr = ['Family', 'Kernels'] + [f'Measured, {KIND[t]}' for t in ('r32', 'r64', 'r128') if t in sums] + \
          ['Smallest observed − design, R16P']
    write(VT / 'orders-families.md', table(hdr, frows))
    det = []
    for k in ks:
        n = short(k['name'])
        row = [f'`{n}`', k['order']]
        for tag in ('r64', 'r128'):
            s = sums[tag][n]
            row.append(f'{float(s["p1"]):.2f}, {float(s["p2"]):.2f}' if s['status'] == 'measured' else '—')
        row.append(f'{k["observed_order"]:.3f}')
        det.append(row)
    write(VT / 'orders-kernels.md', table(['Kernel', 'Design', 'Observed, R8P', 'Observed, R16P',
                                           'Rows at 100 digits (generator)'], det))


