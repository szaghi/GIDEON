#!/usr/bin/env python3
"""Write the generated tables of GIDEON's verification and regression pages from the report data.

Every number of the tables comes from a file, never from this script: the generator's JSON (rows, windows, orders,
findings), the outputs and CSV files of the test programs run by scripts/run_report.sh, the golden files, the recorded
mutation run (notes/mutation-run-*.txt, with the mutants of scripts/mutation_test.py) and the benchmark data
(notes/bench-data). The pages include the tables with <!--@include: ...-->; the directories are excluded from routing
(docs/.vitepress/config.mts, **/_tables/**).

    docs/verification/_tables/*.md     the verification cases (C1-C6, A1-A3)
    docs/regression/_tables/*.md       golden values, mutation testing

Usage: make_tables.py --report DIR   (DIR: the report directory of scripts/run_report.sh, default exe/report)
"""

from __future__ import annotations

import argparse
import csv
import importlib.util
import json
import re
import sys
from collections import Counter, defaultdict
from fractions import Fraction as Fr
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
VT = ROOT / 'docs' / 'verification' / '_tables'
RT = ROOT / 'docs' / 'regression' / '_tables'
HEAD = '<!-- Generated by docs/scripts/make_tables.py from the report data: do not edit. -->\n\n'

FAMILY = {  # family -> (label, order of presentation)
    'fd_face_c': ('FD centred, face value', 0),
    'fd_node_c': ('FD centred, node derivatives d1-d6', 1),
    'fd_facedn_c': ('FD centred, face derivatives d1-d5', 2),
    'fd_face_u': ('FD one-sided, face value (extrapolation)', 3),
    'fd_face_b': ('FD upwind-biased, face value (interpolation)', 4),
    'fv_face_c': ('FV centred, face value', 5),
    'fv_facedn_c': ('FV centred, face derivatives d1-d5', 6),
    'fv_cell_c': ('FV centred, cell-average derivatives d1-d6', 7),
    'fv_face_u': ('FV upwind, face value', 8),
    'fv_facedn_u': ('FV upwind, face derivatives d1-d5', 9),
    'fv_cell_u': ('FV upwind, cell-average derivatives d1-d6', 10),
    'deconv': ('Deconvolution (point value, cell average)', 11),
}
BUILDS = (('r32', 'gfortran, R4P'), ('r64', 'gfortran, R8P'), ('r128', 'gfortran, R16P'),
          ('oac', 'nvfortran -acc, R8P'))
KIND = {'r32': 'R4P', 'r64': 'R8P', 'r128': 'R16P'}


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(HEAD + text.rstrip() + '\n')
    print(f'  {path.relative_to(ROOT)}')


def table(header: list[str], rows: list[list[str]]) -> str:
    out = ['| ' + ' | '.join(header) + ' |', '|' + '---|' * len(header)]
    out += ['| ' + ' | '.join(str(c) for c in r) + ' |' for r in rows]
    return '\n'.join(out) + '\n'


def sci(x: float, digits: int = 1) -> str:
    """x as $a\\cdot10^{b}$ (0 as 0)."""
    if x == 0:
        return '0'
    m, e = f'{x:.{digits}e}'.split('e')
    return f'${m}\\cdot10^{{{int(e)}}}$'


def short(name: str) -> str:
    return name.removeprefix('gideon_')


def last_line(path: Path, prefix: str) -> str:
    """The summary line of a program's output: the last one that starts with prefix and counts the failures."""
    lines = [ln for ln in path.read_text().splitlines() if ln.startswith(prefix) and 'failures' in ln]
    if not lines:
        raise SystemExit(f'{path}: no line starting with {prefix!r}')
    return lines[-1]


def ints(line: str) -> list[int]:
    return [int(v) for v in re.findall(r'(?<![\d.Ee+-])\d+(?![\d.])', line)]


class Report:
    """The report directory: the generator's JSON, the programs' outputs and CSV files."""

    def __init__(self, d: Path) -> None:
        self.d = d
        self.rows = json.loads((d / 'rows.json').read_text())
        self.k = {short(k['name']): k for k in self.rows['kernels']}

    def builds(self) -> list[tuple[str, str]]:
        return [(t, lab) for t, lab in BUILDS if (self.d / t).is_dir()]

    def out(self, tag: str, prog: str) -> Path:
        return self.d / tag / f'{prog}.txt'

    def summary(self, tag: str) -> dict[str, dict[str, str]]:
        bits = {'r32': 32, 'r64': 64, 'r128': 128, 'oac': 64}[tag]
        f = self.d / tag / f'order-summary-r{bits}.csv'
        return {r['kernel']: r for r in csv.DictReader(f.open())}


# ---------------------------------------------------------------------------------------------------------------------
# C1: the rows by their meaning (the generator)
# ---------------------------------------------------------------------------------------------------------------------
def rows_tables(r: Report) -> None:
    ks = r.rows['kernels']
    fam = defaultdict(list)
    for k in ks:
        fam[k['family']].append(k)
    lines = []
    for f, (label, _) in sorted(FAMILY.items(), key=lambda x: x[1][1]):
        g = fam[f]
        margin = min(g, key=lambda k: k['observed_order'] - k['order'])
        lines.append([label, len(g), f'{min(k["order"] for k in g)}-{max(k["order"] for k in g)}',
                      f'{min(k["hi"] - k["lo"] + 1 for k in g)}-{max(k["hi"] - k["lo"] + 1 for k in g)}',
                      f'{margin["observed_order"] - margin["order"]:+.3f} (`{short(margin["name"])}`)'])
    lines.append(['**all**', len(ks), '', '', ''])
    write(VT / 'rows-families.md', table(['Family', 'Kernels', 'Orders', 'Window (cells or nodes)',
                                          'Smallest observed − design order (100 digits)'], lines))
    findings = r.rows['findings']
    checked = next(int(m.group(1)) for f in findings if (m := re.match(r'checked (\d+) ADAM rows', f)))
    om = next(f for f in findings if f.startswith('orders:'))
    bad = [f for f in findings if f.startswith(('MISMATCH', 'NOT GENERATED', 'ORDER'))]
    mirrors = sum(1 for k in ks if k['bias'] in ('ul', 'bl'))  # every left-side kernel: one-sided and biased
    m = re.match(r'orders: (\d+) rows, smallest margin ([+-][\d.]+) \((\w+), observed ([\d.]+)\)', om)
    write(VT / 'rows-checks.md', table(['Check', 'Result'], [
        ['rows derived (exact rationals)', len(ks)],
        ['3-D operators assembled from them', len(r.rows['operators_3d'])],
        ['ADAM rows cross-checked (non-zero ones of its tables)', f'{checked}, mismatches {sum(1 for f in bad if f.startswith("MISMATCH"))}'],
        ['left-side rows solved independently and found to be mirrors', mirrors],
        ['orders at 100 digits ($h = 2^{-11}, 2^{-12}$), bound design − 0.25',
         f'{m.group(1)} rows, smallest margin {m.group(2)} (`{short(m.group(3))}`, observed {m.group(4)})'],
        ['findings that fail the generator', len(bad)],
    ]))
    # the FV centred cell derivatives and the FD centred node derivatives: the same weights
    same = [(short(k['name']), short('gideon_fd' + k['name'][9:])) for k in ks if k['family'] == 'fv_cell_c']
    eq = sum(1 for a, b in same if r.k[a]['weights'] == r.k[b]['weights'])
    write(VT / 'rows-fd-fv.md', f'{eq} of the {len(same)} centred cell-average derivatives `fv_dN_cP` have the '
          'weights of the node derivative `fd_dN_cP` of the same window, exactly (the rows of the JSON compared as '
          'fractions).\n')


