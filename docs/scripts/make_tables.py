def golden_tables(r: Report) -> None:
    src = (ROOT / 'src/tests/gideon_test_golden.F90').read_text()
    read = dict(re.findall(r"GOLDEN = 'src/tests/golden/(\S+)'\s*\n\s*real\(R_P\),\s*parameter :: TOL = (\S+)_R_P", src))
    kind_of = lambda name: 'R4P' if '_r4_' in name else 'R16P' if '_r16_' in name else 'R8P'  # noqa: E731
    tol = {kind_of(name): t for name, t in read.items()}  # the tolerance is the kind's, every version alike
    nst = re.search(r'NST = (\d+)_I4P', src).group(1)
    rows = []
    for f in sorted((ROOT / 'src/tests/golden').glob('gideon_golden_*.txt')):
        lines = f.read_text().splitlines()
        writer = lines[0].split('Written by ')[1]
        opt = re.search(r'-O\d', lines[1])
        nvals = sum(1 for ln in lines if not ln.startswith('#'))
        kind = kind_of(f.name)
        t = tol[kind]
        rows.append([f'`{f.name}`', kind, nvals, f'{writer}, `{opt.group(0) if opt else ""}`', sci(float(t), 0),
                     'yes' if f.name in read else 'no (kept)'])
    write(RT / 'golden-files.md', table(['File', 'Kind', 'Values', 'Written by', 'Tolerance (of the magnitude)',
                                         'Read by the test'], rows))
    write(RT / 'golden-count.md', f'{len(r.rows["kernels"])} kernels × {nst} windows = '
          f'{len(r.rows["kernels"]) * int(nst)} values per file.\n')
    brows = []
    for tag, lab in r.builds():
        line = last_line(r.out(tag, 'gideon_test_golden'), 'gideon_test_golden: ')
        m = re.search(r'(\d+) values, bitwise (\d+), worst relative difference\s+(\S+), failures (\d+)', line)
        nv, nb, w, nf = m.groups()
        brows.append([lab, nv, f'{nb} ({100 * int(nb) / int(nv):.1f} %)', sci(float(w)), nf])
    write(RT / 'golden-builds.md', table(['Build', 'Values', 'Bitwise equal', 'Worst difference / magnitude',
                                          'Failures'], brows))


def mutation_tables(run: Path, prefix: str = 'mutation') -> None:
    spec = importlib.util.spec_from_file_location('mutation_test', ROOT / 'scripts' / 'mutation_test.py')
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    mutants = {m[0]: m for m in mod.MUTANTS}
    rows = []
    killed_by = {}
    total = None
    for line in run.read_text().splitlines():
        m = re.match(r'(\S+)\s+killed by (.*)$', line)
        if m:
            killed_by[m.group(1)] = [t.strip() for t in m.group(2).split(',')]
        m2 = re.match(r'(\d+) of (\d+) mutants killed', line)
        if m2:
            total = (int(m2.group(1)), int(m2.group(2)))
        m3 = re.match(r'(\S+)\s+SURVIVED', line)
        if m3:
            killed_by[m3.group(1)] = []
    for name, (_, f, _, old, new) in mutants.items():
        tests = killed_by.get(name)
        if tests is None:
            raise SystemExit(f'{run}: no result for the mutant {name}')
        rows.append([f'`{name}`', f'`{Path(f).name}`', f'`{old}` → `{new}`',
                     ', '.join(t.removeprefix('gideon_test_') for t in tests) or '**survived**', len(tests)])
    write(RT / f'{prefix}-mutants.md', table(['Mutant', 'File', 'Change', 'Killed by (gideon_test_…)', 'Tests'], rows))
    date = re.search(r'\d{4}-\d{2}-\d{2}', run.name).group(0)
    write(RT / f'{prefix}-total.md', f'**{total[0]} of {total[1]} mutants killed** (`{run.name}`, {date}).\n')
    count = Counter(t for v in killed_by.values() for t in v)
    only = Counter(v[0] for v in killed_by.values() if len(v) == 1)
    trows = [[f'`{t}`', c, only.get(t, 0)] for t, c in count.most_common()]
    write(RT / f'{prefix}-tests.md', table(['Test', 'Mutants it kills', 'Mutants only it kills'], trows))


def current_mutation_run() -> Path:
    """The recorded run of the current mutants: the newest notes/mutation-run-*.txt (by modification order of the names,
    then the file name) that lists exactly the mutants of scripts/mutation_test.py. A run of an older mutant list
    documents an older suite, not this one."""
    src = (ROOT / 'scripts' / 'mutation_test.py').read_text()
    block = src[src.index('MUTANTS = ['):]
    current = set(re.findall(r"^\s+\('([\w-]+)',", block[:block.index('\n]')], re.M))
    runs = sorted((ROOT / 'notes').glob('mutation-run-*.txt'))
    matching = [f for f in runs
                if set(re.findall(r'^([\w-]+)\s+(?:killed|SURVIVED)', f.read_text(), re.M)) == current]
    if not matching:
        raise SystemExit('make_tables: no notes/mutation-run-*.txt lists the current mutants: run scripts/mutation_test.py')
    return matching[-1]


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--report', type=Path, default=ROOT / 'exe' / 'report')
    ap.add_argument('--mutation-run', type=Path, default=None,
                    help='the recorded mutation run (default: the newest notes/mutation-run-*.txt whose mutants are '
                         'exactly those of scripts/mutation_test.py)')
    args = ap.parse_args()
    r = Report(args.report)
    rows_tables(r)
    exactness_tables(r)
    properties_tables(r)
    adam_tables(r)
    device_tables(r)
    orders_tables(r)
    operators3d_tables(r)
    spectral_tables(r)
    golden_tables(r)
    run = args.mutation_run or current_mutation_run()
    mutation_tables(run)
    reruns = sorted(r.d.glob('mutation-run-*.txt'))
    if reruns:  # a run of the current suite, kept in the report (scripts/mutation_test.py > <report>/mutation-run-*.txt)
        mutation_tables(reruns[-1], 'mutation-rerun')
    return 0


if __name__ == '__main__':
    sys.exit(main())
