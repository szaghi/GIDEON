# C3, C4: properties and dispatch
# ---------------------------------------------------------------------------------------------------------------------
def properties_tables(r: Report) -> None:
    ks = r.rows['kernels']
    n_mirror = sum(1 for k in ks if k['bias'] in ('ul', 'bl'))
    n_centred = sum(1 for k in ks if k['bias'] == 'c')
    n_der = sum(1 for k in ks if k['n'] >= 1)
    write(VT / 'properties-counts.md', table(['Property', 'Kernels', 'Trials', 'Comparison'], [
        ['left side = $(-1)^n$ right side on mirrored data', n_mirror, 20, 'bitwise'],
        ['centred kernel on data of the odd symmetry returns 0', n_centred, 20, 'bitwise'],
        ['$k(8q) = 8\\,k(q)$, $k(q, 2\\,\\Delta s) = k(q, \\Delta s)/2^n$', len(ks), 20, 'bitwise'],
        ['constant data: 0 for a derivative (pair or flux-difference form), the constant otherwise',
         f'{n_der} derivatives, {len(ks) - n_der} values', 1, 'bitwise (derivatives), 64 eps Σ\\|c\\| (values)'],
    ]))
    rows = []
    for tag, lab in r.builds():
        p = ints(last_line(r.out(tag, 'gideon_test_properties'), 'gideon_test_properties:'))
        d = ints(last_line(r.out(tag, 'gideon_test_dispatch'), 'gideon_test_dispatch:'))
        rows.append([lab, p[0], p[1], d[0], d[1]])
    write(VT / 'properties-builds.md', table(['Build', 'Kernels (properties)', 'Failures', 'Kernels (dispatch)',
                                              'Failures'], rows))
    drows = []
    for d in r.rows['dispatchers']:
        orders = sorted(d['orders'])
        span = ', '.join(map(str, orders)) if len(orders) <= 2 else f'{orders[0]}-{orders[-1]}' + (
            ' (even)' if all(o % 2 == 0 for o in orders) and orders[-1] - orders[0] == 2 * (len(orders) - 1) else '')
        drows.append([f'`{short(d["name"])}`', len(orders), span, f'`q({d["window"][0]}:{d["window"][1]})`',
                      d['nan_order']])
    groups = r.rows['dispatchers']
    write(VT / 'dispatch-list.md', table(['Dispatcher', 'Kernels', 'Orders', 'Window', 'Order of the NaN check'], drows))
    n3 = len({re.sub(r'\d+$', '', o['name']) for o in r.rows['operators_3d']})
    write(VT / 'dispatch-counts.md', f'{len(groups)} dispatchers of the 1-D kernels, {n3} of the 3-D operators.\n')


