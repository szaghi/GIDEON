ADAM_GROUP = [  # (regex on the test's labels, the group shown, the audit item)
    (r'^fd face$', 'FD centred face', ''), (r'^fd d$', 'FD centred d1-d6', 'C (zero rows)'),
    (r'^fv face$', 'FV centred face', ''), (r'^fv face d$', 'FV centred face d1-d5', 'C (zero rows)'),
    (r'^fv d$', 'FV centred cell d1-d6', 'C (zero rows)'),
    (r'^fv point$|^fd average$', 'Deconvolution', ''),
    (r'^fv face ur$', 'FV upwind face, right side (`rupwind`)', ''),
    (r'^fv face ul( \(A\))?$', 'FV upwind face, left side (`lupwind`)', 'A'),
    (r'^fv d1 ur$', 'FV upwind d1, right side (`rupwind`)', 'B (window), F'),
    (r'^fv d1 ul( \(A\))?$', 'FV upwind d1, left side (`lupwind`)', 'A, F'),
    (r'^fv d ul$', 'FV upwind d2-d5, left side (ADAM `rupwind`)', 'C, F'),
    (r'^fv d ur$', 'FV upwind d2-d5, right side (ADAM `lupwind`)', 'C, F'),
    (r'^fv face d ul$', 'FV upwind face d1-d4, left side (ADAM `rupwind_d`)', 'F'),
    (r'^fv face d ur$', 'FV upwind face d1-d4, right side (ADAM `lupwind_d`)', 'F'),
    (r'^fv d6 rupwind$', 'FV upwind d6 (ADAM: none)', 'C'),
    (r'\(FNL\)$', '3-D operators, FNL (directional) signature', ''),
    (r'\(CPU\)$', '3-D operators, CPU (cube) signature', ''),
]


def adam_rows(r: Report) -> tuple[list[list], dict[str, int]]:
    data = list(csv.DictReader((r.d / 'r64' / 'adam.csv').open()))
    agg: dict[str, Counter] = {g: Counter() for _, g, _ in ADAM_GROUP}
    worst: dict[str, float] = defaultdict(float)
    item = {g: a for _, g, a in ADAM_GROUP}
    for row in data:
        g = next((g for rx, g, _ in ADAM_GROUP if re.search(rx, row['operator'])), None)
        if g is None:
            raise SystemExit(f'adam.csv: no group for {row["operator"]!r}')
        agg[g][row['class']] += 1
        if row['class'] == 'tolerance':
            worst[g] = max(worst[g], float(row['difference']))
    rows = []
    for _, g, _ in ADAM_GROUP:
        c = agg[g]
        rows.append([g, c['bitwise'], c['tolerance'], c['defect'], c['absent'],
                     sci(worst[g]) if c['tolerance'] else '', item[g]])
    tot = Counter(row['class'] for row in data)
    return rows, tot


def adam_counts(line: str) -> tuple[int, ...]:
    """bitwise, within tolerance, defects, absent, failures from the summary line of gideon_test_adam."""
    m = re.search(r'bitwise (\d+), within tolerance (\d+), ADAM defects reproduced (\d+), .*\) (\d+), failures (\d+)',
                  line)
    return tuple(int(v) for v in m.groups())


def adam_tables(r: Report) -> None:
    rows, tot = adam_rows(r)
    line = last_line(r.out('r64', 'gideon_test_adam'), 'gideon_test_adam:')
    b, t, d, a, f = adam_counts(line)
    if (b, t, d, a) != (tot['bitwise'], tot['tolerance'], tot['defect'], tot['absent']):
        raise SystemExit('adam.csv and the output of gideon_test_adam disagree')
    rows.append(['**total**', f'**{b}**', f'**{t}**', f'**{d}**', f'**{a}**', '', ''])
    write(VT / 'adam-groups.md', table(['ADAM operators', 'Bitwise', 'Within 64 eps', 'ADAM defect reproduced',
                                        'ADAM returns 0', 'Largest difference', 'Audit'], rows))
    brows = []
    for tag, lab in r.builds():
        p = r.out(tag, 'gideon_test_adam')
        if p.exists():
            brows.append([lab, *adam_counts(last_line(p, 'gideon_test_adam:'))])
    write(VT / 'adam-builds.md', table(['Build', 'Bitwise', 'Within tolerance', 'Defects reproduced',
                                        'ADAM zero rows', 'Failures'], brows))


