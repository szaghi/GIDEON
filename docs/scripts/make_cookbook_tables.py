#!/usr/bin/env python3
"""Generate the tables of the cookbook and of the API page from the compiled kernels' sources.

Every number comes from the Fortran the library compiles (src/lib/*.F90): the window `q(LO:HI)` each kernel declares,
the rows of gideon_tables and the kernels that read them, the dispatchers' window expressions. Nothing is typed.

Written (all excluded from the site's page list by `**/_tables/**`, included by the pages):

    docs/cookbook/_tables/orders.md     the orders of every operator and the points of each window (cookbook/choose)
    docs/cookbook/_tables/ghosts.md     the ghost cells each operator needs, by order (cookbook/ghosts)
    docs/guide/_tables/api-dispatch.md  the 1-D run-time order dispatchers, their orders and windows (guide/api)
    docs/guide/_tables/api-rows.md      the named rows of gideon_tables and the kernels reading them (guide/api)

Usage (from the repository root):
    python3 docs/scripts/make_cookbook_tables.py           write the tables
    python3 docs/scripts/make_cookbook_tables.py --check   exit 1 if a table on disk differs from the sources
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
LIB = ROOT / 'src' / 'lib'
KERNEL_MODULES = ('gideon_fd_centred', 'gideon_fd_upwind', 'gideon_fv_centred', 'gideon_fv_upwind',
                  'gideon_deconvolution')
HEADER = '<!-- Generated by docs/scripts/make_cookbook_tables.py from src/lib/*.F90: do not edit. -->\n'
NAME = re.compile(r'^gideon_(fd|fv)_(.+)_(c|ur|ul|br|bl)(\d+)$')


@dataclass
class Kernel:
    """A compiled kernel: its name, its parts, its window."""

    name: str
    data: str
    op: str
    bias: str
    order: int
    lo: int
    hi: int
    body: str

    @property
    def group(self) -> str:
        """The run-time dispatcher of the kernel: its name without the order."""
        return f'gideon_{self.data}_{self.op}_{self.bias}'

    @property
    def at_face(self) -> bool:
        """True for an operator whose result sits at a face (between offsets 0 and 1)."""
        return self.op == 'face' or self.op.startswith('face_')

    def ghosts(self) -> tuple[int, int]:
        """Ghost cells (left, right) to apply the kernel at every point of 1..N (faces: the N+1 faces of 1..N).

        A node or cell operator at point i reads i+LO..i+HI: for i = 1..N the data reach 1+LO and N+HI. A face
        operator at the face between i and i+1 reads the same offsets; the N+1 faces of 1..N are i = 0..N, so the data
        reach LO and N+HI.
        """
        first = 0 if self.at_face else 1
        return max(0, 1 - (first + self.lo)), max(0, self.hi)


def parse_kernels() -> list[Kernel]:
    """Every kernel of the four kernel modules, in the order of the sources."""
    out = []
    for mod in KERNEL_MODULES:
        text = (LIB / f'{mod}.F90').read_text()
        for m in re.finditer(r'pure subroutine (gideon_\w+)\(q.*?\n(.*?)endsubroutine \1', text, re.DOTALL):
            name, body = m.group(1), m.group(2)
            w = re.search(r'::\s*q\((-?\d+):(-?\d+)\)', body)
            parts = NAME.match(name)
            if w is None or parts is None:
                raise ValueError(f'{mod}: cannot read the window or the name of {name}')
            data, op, bias, order = parts.groups()
            out.append(Kernel(name, data, op, bias, int(order), int(w.group(1)), int(w.group(2)), body))
    return out


def parse_3d() -> list[tuple[str, int]]:
    """(name, half-width per axis) of every 3-D operator kernel."""
    text = (LIB / 'gideon_operators_3d.F90').read_text()
    out = []
    for m in re.finditer(r'pure subroutine (gideon_\w+_c\d+)\(.*?\n(.*?)endsubroutine \1', text, re.DOTALL):
        w = re.search(r'\((-?\d+):(\d+)\)', m.group(2))
        if w is None or int(w.group(1)) != -int(w.group(2)):
            raise ValueError(f'cannot read the window of {m.group(1)}')
        out.append((m.group(1), int(w.group(2))))
    return out


def groups(ks: list[Kernel]) -> dict[str, list[Kernel]]:
    """Kernels by run-time dispatcher, in the order of the sources."""
    out: dict[str, list[Kernel]] = {}
    for k in ks:
        out.setdefault(k.group, []).append(k)
    return out


RESULT = {'face': 'value at the face', 'point': 'point value at the cell centre', 'average': 'cell average'}


def result(k: Kernel) -> str:
    """What the kernel returns, in words."""
    if k.op in RESULT:
        return RESULT[k.op]
    n = k.op.removeprefix('face_')
    if k.op.startswith('face_'):
        return f'{n} at the face'
    return f'{n} at the node' if k.data == 'fd' else f'{n} averaged over the cell'


DATA = {'fd': 'point values', 'fv': 'cell averages'}
SIDE = {'c': 'centred', 'ur': 'right side', 'ul': 'left side', 'br': 'biased right', 'bl': 'biased left'}


def table_orders(ks: list[Kernel]) -> str:
    """Orders of every operator, with the points of the window of each order."""
    lines = [HEADER, '| Operator (dispatcher) | Data | Result | Stencil | Orders: points in the window |',
             '|---|---|---|---|---|']
    for name, g in groups(ks).items():
        k0 = g[0]
        cells = ', '.join(f'{k.order}: {k.hi - k.lo + 1}' for k in g)
        lines.append(f'| `{name}` | {DATA[k0.data]} | {result(k0)} | {SIDE[k0.bias]} | {cells} |')
    return '\n'.join(lines) + '\n'


def fmt_ghosts(left: int, right: int) -> str:
    """One number when both sides need the same, `left / right` otherwise."""
    return str(left) if left == right else f'{left} / {right}'


def table_ghosts(ks: list[Kernel], k3: list[tuple[str, int]]) -> str:
    """Ghost cells by operator and order; the upwind pairs; the 3-D operators."""
    gs = groups(ks)
    orders = sorted({k.order for k in ks})
    head = '| Operator | ' + ' | '.join(str(o) for o in orders) + ' |'
    rule = '|---|' + '---|' * len(orders)
    lines = [HEADER, '**Every operator, by order** (left / right when they differ; blank: no kernel of that order)', '',
             head, rule]
    for name, g in gs.items():
        by = {k.order: fmt_ghosts(*k.ghosts()) for k in g}
        lines.append(f'| `{name.removeprefix("gideon_")}` | ' + ' | '.join(by.get(o, '') for o in orders) + ' |')
    lines += ['', '**An upwind pair** (both sides of a face or cell, the side chosen per point by the flow)', '',
              head, rule]
    for name, g in gs.items():
        if not name.endswith('_ur'):
            continue
        twin = {k.order: k for k in gs[name[:-1] + 'l']}
        by = {}
        for k in g:
            (l1, r1), (l2, r2) = k.ghosts(), twin[k.order].ghosts()
            by[k.order] = fmt_ghosts(max(l1, l2), max(r1, r2))
        label = name.removeprefix('gideon_')[:-3] + '_ur + _ul'
        lines.append(f'| `{label}` | ' + ' | '.join(by.get(o, '') for o in orders) + ' |')
    by3: dict[str, dict[int, int]] = {}
    for name, s in k3:
        m = re.match(r'(gideon_\w+_c)(\d+)$', name)
        by3.setdefault(m.group(1), {})[int(m.group(2))] = s
    lines += ['', '**The 3-D operators** (per axis, along the axis only: no edge or corner ghosts)', '', head, rule]
    for name, d in by3.items():
        lines.append(f'| `{name.removeprefix("gideon_")}` | ' + ' | '.join(str(d[o]) if o in d else '' for o in orders)
                     + ' |')
    return '\n'.join(lines) + '\n'


def table_dispatch() -> str:
    """The 1-D dispatchers: arguments, orders, window."""
    text = (LIB / 'gideon_dispatch.F90').read_text()
    lines = [HEADER, '| Dispatcher | Arguments | Orders | Window `q` |', '|---|---|---|---|']
    for m in re.finditer(r'pure subroutine (gideon_\w+)\((.*?)\)\n\s*!< .*?order in \{(.*?)\}\.\n(.*?)endsubroutine',
                         text, re.DOTALL):
        w = re.search(r'::\s*q\((.*?)\)\s*!<', m.group(4))
        lines.append(f'| `{m.group(1)}` | `({m.group(2)})` | {m.group(3)} | `q({w.group(1)})` |')
    return '\n'.join(lines) + '\n'


def table_rows(ks: list[Kernel]) -> str:
    """The named rows of gideon_tables, their bounds and the kernels that read them."""
    text = (LIB / 'gideon_tables.F90').read_text()
    lines = [HEADER, '| Row | Bounds | Read by |', '|---|---|---|']
    for m in re.finditer(r'parameter :: (\w+)\((-?\d+):(\d+)\)', text):
        row = m.group(1)
        users = [k.name for k in ks if re.search(rf'\b{row}\(', k.body)]
        lines.append(f'| `{row}` | `({m.group(2)}:{m.group(3)})` | ' + ', '.join(f'`{u}`' for u in users) + ' |')
    return '\n'.join(lines) + '\n'


def main() -> int:
    """Write the tables, or check them with --check."""
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('--check', action='store_true', help='exit 1 if a table on disk is not the generated one')
    args = ap.parse_args()
    ks = parse_kernels()
    k3 = parse_3d()
    files = {
        ROOT / 'docs/cookbook/_tables/orders.md': table_orders(ks),
        ROOT / 'docs/cookbook/_tables/ghosts.md': table_ghosts(ks, k3),
        ROOT / 'docs/guide/_tables/api-dispatch.md': table_dispatch(),
        ROOT / 'docs/guide/_tables/api-rows.md': table_rows(ks),
    }
    stale = []
    for path, text in files.items():
        if path.exists() and path.read_text() == text:
            continue
        if args.check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f'written {path.relative_to(ROOT)}')
    print(f'{len(ks)} kernels, {len(k3)} 3-D operators')
    if stale:
        print('stale: ' + ', '.join(stale))
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
